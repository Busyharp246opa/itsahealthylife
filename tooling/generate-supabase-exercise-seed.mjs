import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const root = resolve(import.meta.dirname, "..");
const sourcePath = resolve(root, "public/data/exercises.json");
const outputPath = resolve(root, "supabase/seeds/10_exercises.sql");
const source = JSON.parse(await readFile(sourcePath, "utf8"));

const records = source.map((exercise) => ({
  id: exercise.id,
  name: exercise.name,
  category: exercise.category,
  body_part: exercise.bodyPart,
  equipment: exercise.equipment,
  target: exercise.target,
  muscle_group: exercise.muscleGroup,
  secondary_muscles: exercise.secondaryMuscles ?? [],
  instructions: exercise.instructions?.en ?? "",
  steps: exercise.steps?.en ?? [],
  instructions_by_locale: exercise.instructions ?? {},
  instruction_steps_by_locale: exercise.steps ?? {},
  media_id: exercise.mediaId,
  image_path: exercise.imagePath,
  gif_path: exercise.gifPath,
  media_attribution: exercise.mediaAttribution,
  source_created_at: exercise.sourceCreatedAt,
  content_hash: exercise.contentHash,
}));

const json = JSON.stringify(records).replaceAll("$fitcircle$", "$fit_circle$");
const sql = `-- Generated by tooling/generate-supabase-exercise-seed.mjs. Do not edit by hand.
insert into public.exercise_catalog (
  id,
  name,
  category,
  body_part,
  equipment,
  target,
  muscle_group,
  secondary_muscles,
  instructions,
  steps,
  instructions_by_locale,
  instruction_steps_by_locale,
  media_id,
  image_path,
  gif_path,
  media_attribution,
  source_created_at,
  content_hash
)
select
  item.id,
  item.name,
  item.category,
  item.body_part,
  item.equipment,
  item.target,
  item.muscle_group,
  item.secondary_muscles,
  item.instructions,
  item.steps,
  item.instructions_by_locale,
  item.instruction_steps_by_locale,
  item.media_id,
  item.image_path,
  item.gif_path,
  item.media_attribution,
  item.source_created_at,
  item.content_hash
from jsonb_to_recordset($fitcircle$${json}$fitcircle$::jsonb) as item(
  id text,
  name text,
  category text,
  body_part text,
  equipment text,
  target text,
  muscle_group text,
  secondary_muscles text[],
  instructions text,
  steps text[],
  instructions_by_locale jsonb,
  instruction_steps_by_locale jsonb,
  media_id text,
  image_path text,
  gif_path text,
  media_attribution text,
  source_created_at timestamptz,
  content_hash text
)
on conflict (id) do update set
  name = excluded.name,
  category = excluded.category,
  body_part = excluded.body_part,
  equipment = excluded.equipment,
  target = excluded.target,
  muscle_group = excluded.muscle_group,
  secondary_muscles = excluded.secondary_muscles,
  instructions = excluded.instructions,
  steps = excluded.steps,
  instructions_by_locale = excluded.instructions_by_locale,
  instruction_steps_by_locale = excluded.instruction_steps_by_locale,
  media_id = excluded.media_id,
  image_path = excluded.image_path,
  gif_path = excluded.gif_path,
  media_attribution = excluded.media_attribution,
  source_created_at = excluded.source_created_at,
  content_hash = excluded.content_hash;
`;

await writeFile(outputPath, sql, "utf8");
console.log(`Wrote ${records.length} exercises to ${outputPath}`);
